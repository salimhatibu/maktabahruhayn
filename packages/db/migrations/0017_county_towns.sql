-- Delivery towns an admin can add to or remove from a county. They sit next to
-- the county's fixed sub-counties in the address form, and are priced by the
-- county they are listed under.
CREATE TABLE county_town (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  county_code TEXT NOT NULL,
  name        TEXT NOT NULL COLLATE NOCASE,
  UNIQUE (county_code, name)
);

