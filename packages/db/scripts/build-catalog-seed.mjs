/**
 * Turns the 22 real titles in packages/db/seed-data into SQL that loads
 * straight into D1, so a fresh database has a working catalogue.
 *
 *   node packages/db/scripts/build-catalog-seed.mjs
 *   pnpm db:seed:local
 *
 * Cover images are already committed under the storefront's public/catalog,
 * where the Worker serves them from Cloudflare's CDN with no R2 setup; this
 * copies them again only if the original files are present. Images uploaded
 * later through the admin go to R2 instead.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../../..")
const catalogDir = path.join(repo, "packages/db/seed-data")
const publicDir = path.join(repo, "apps/storefront/public/catalog")
const outFile = path.join(repo, "packages/db/seed/catalog.sql")

// Read straight from the TypeScript source, which needs no build step.
const { DEFAULT_SETTINGS } = await import(path.join(repo, "packages/db/src/settings-defaults.ts"))

const CATEGORIES = [
  { handle: "quran-mushaf", name: "Qur'an & Mushaf" },
  { handle: "tafsir", name: "Tafsir" },
  { handle: "hadith", name: "Hadith" },
  { handle: "fiqh-aqidah", name: "Fiqh & Aqidah" },
  { handle: "seerah-history", name: "Seerah & History" },
  { handle: "islamic-living", name: "Islamic Living" },
  { handle: "islamic-education", name: "Islamic Education & Arabic" },
  { handle: "childrens-books", name: "Children's Books" },
  { handle: "gifts", name: "Gifts & Calendars" },
  { handle: "general-islamic", name: "General Islamic" },
  { handle: "arabic-learning", name: "Arabic Learning" },
  { handle: "marriage-family", name: "Marriage & Family" },
]

/** Short, readable code used as the system SKU, stable for a given seed. */
function systemSku(seed) {
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
  let out = ""
  let n = h >>> 0
  for (let i = 0; i < 6; i++) {
    out += alphabet[n % alphabet.length]
    n = Math.floor(n / alphabet.length) || h >>> (i + 1)
  }
  return `MR-${out}`
}

function lit(value) {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL"
  if (typeof value === "boolean") return value ? "1" : "0"
  const text = typeof value === "object" ? JSON.stringify(value) : String(value)
  return `'${text.replace(/'/g, "''")}'`
}

/**
 * OR IGNORE keeps the seed safe to re-run: existing rows are left alone rather
 * than deleted and recreated, which would cascade through a catalogue that may
 * already have orders pointing at it.
 */
function insert(table, row) {
  const cols = Object.keys(row)
  return `INSERT OR IGNORE INTO ${table} (${cols.join(", ")}) VALUES (${cols.map((c) => lit(row[c])).join(", ")});`
}

const minor = (major) => (major === null || major === undefined ? null : Math.round(Number(major) * 100))

const { books } = JSON.parse(fs.readFileSync(path.join(catalogDir, "books.json"), "utf8"))
const sql = [
  "-- Generated by packages/db/scripts/build-catalog-seed.mjs - do not edit by hand.",
  `-- ${books.length} titles from packages/db/seed-data/books.json`,
  "",
  insert("stock_location", { id: "loc_main", name: "Nairobi" }),
  // Only the base rate is seeded. Every other currency is converted at read
  // time once the FX sync has run; until then shoppers are priced in USD
  // rather than at an invented rate.
  insert("fx_rate", { currency_code: "usd", rate: 1, fetched_at: new Date().toISOString() }),
  "",
]

for (const [i, c] of CATEGORIES.entries()) {
  sql.push(insert("category", { id: `cat_${c.handle}`, handle: c.handle, name: c.name, rank: i }))
}
sql.push("")

fs.mkdirSync(publicDir, { recursive: true })
let copied = 0

books.forEach((book, index) => {
  const id = `prd_${book.handle}`
  const variantId = `var_${book.handle}`

  sql.push(
    insert("product", {
      id,
      product_number: 101 + index,
      handle: book.handle,
      title: book.title,
      subtitle: book.subtitle || null,
      description_html: book.description ? `<p>${String(book.description).replace(/</g, "&lt;")}</p>` : "",
      status: "published",
      thumbnail: book.images?.length ? `/catalog/${book.images[0]}` : null,
      unit: "item",
      product_type: "standard",
      delivery_type: "physical",
      primary_category_id: book.category ? `cat_${book.category}` : null,
      option_title: "Format",
      option_display: "buttons",
      shipping_size: "small",
      pages: book.pages || null,
      series: book.series || null,
      release_date: null,
      preorder: book.preorder ? 1 : 0,
      editorial_reviews: "[]",
    })
  )

  if (book.category) {
    sql.push(insert("product_category", { product_id: id, category_id: `cat_${book.category}` }))
  }
  for (const tag of book.tags || []) {
    sql.push(insert("product_tag", { product_id: id, value: tag }))
  }

  ;(book.images || []).forEach((file, n) => {
    const from = path.join(catalogDir, "images", file)
    if (fs.existsSync(from)) {
      fs.copyFileSync(from, path.join(publicDir, file))
      copied += 1
    }
    sql.push(insert("product_image", { id: `img_${book.handle}_${n}`, product_id: id, url: `/catalog/${file}`, rank: n }))
  })

  const b = book.book || {}
  sql.push(
    insert("book", {
      product_id: id,
      title_arabic: b.title_arabic || null,
      author: b.author || null,
      translator: b.translator || null,
      commentator_tahqeeq: b.commentator_tahqeeq || null,
      publisher: b.publisher || null,
      binding_type: b.binding_type || null,
      script_type: b.script_type || null,
      language: b.language || null,
      volume_count: b.volume_count || null,
      isbn_10: b.isbn_10 || null,
      isbn_13: b.isbn_13 || null,
      sample_pdf_url: null,
    })
  )

  const [length, width] = book.dimensions_cm || []
  sql.push(
    insert("variant", {
      id: variantId,
      product_id: id,
      title: book.format || "Standard",
      option_value: book.format || "Standard",
      system_sku: systemSku(variantId),
      manage_inventory: 1,
      allow_backorder: book.allow_backorder ? 1 : 0,
      weight_g: book.weight_g || null,
      length_cm: length || null,
      width_cm: width || null,
      rank: 0,
    })
  )

  sql.push(
    insert("variant_price", {
      variant_id: variantId,
      currency_code: "usd",
      kind: "base",
      amount_minor: minor(book.sale_price_usd ?? book.price_usd),
    })
  )
  if (book.sale_price_usd) {
    // The struck-through price is what it was before the sale.
    sql.push(
      insert("variant_price", {
        variant_id: variantId,
        currency_code: "usd",
        kind: "sale",
        amount_minor: minor(book.price_usd),
      })
    )
  }

  sql.push(
    insert("inventory_level", {
      variant_id: variantId,
      location_id: "loc_main",
      stocked_quantity: Number(book.stock) || 0,
      reserved_quantity: 0,
      version: 0,
    }),
    ""
  )
})

for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
  sql.push(insert("store_setting", { key, value: JSON.stringify(value), updated_at: new Date().toISOString() }))
}

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, sql.join("\n") + "\n")
console.log(`Wrote ${outFile}`)
console.log(`  ${books.length} products, ${CATEGORIES.length} categories, ${copied} images copied to apps/storefront/public/catalog`)
